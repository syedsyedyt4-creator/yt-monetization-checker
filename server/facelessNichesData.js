/**
 * Returns dynamically rotated niches for today based on calendar day
 */
export function getDailyNiches() {
  const now = new Date();
  // Generate deterministic day index e.g. 1-366
  const startOfYear = new Date(now.getFullYear(), 0, 0);
  const diff = now - startOfYear;
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);

  // Rotate list so top niche changes every single day!
  const rotationIndex = dayOfYear % ALL_FACELESS_NICHES.length;
  const rotated = [
    ...ALL_FACELESS_NICHES.slice(rotationIndex),
    ...ALL_FACELESS_NICHES.slice(0, rotationIndex)
  ];

  // Dynamically assign daily trending badges and velocity
  const dailyRanked = rotated.map((niche, idx) => {
    let dailyBadge = niche.badge;
    let viralScore = 99 - (idx * 3);
    if (idx === 0) {
      dailyBadge = `🔥 #1 Trending Today (${now.toLocaleDateString('en-US', { month: 'short', day: 'numeric' })})`;
      viralScore = 99;
    } else if (idx === 1) {
      dailyBadge = `📈 Exploding This Week (+${35 + (dayOfYear % 25)}% Views)`;
      viralScore = 96;
    } else if (idx === 2) {
      dailyBadge = `💎 Highest RPM Pick for ${now.toLocaleDateString('en-US', { month: 'long' })}`;
      viralScore = 94;
    }

    return {
      ...niche,
      dailyBadge,
      dailyRank: idx + 1,
      viralScore: `${Math.max(78, viralScore)}% Velocity`,
      lastUpdatedDate: now.toLocaleDateString('en-US', { weekday: 'long', year: 'numeric', month: 'long', day: 'numeric' })
    };
  });

  return {
    niches: dailyRanked,
    featuredToday: dailyRanked[0],
    todayDate: now.toLocaleDateString('en-US', { weekday: 'long', month: 'long', day: 'numeric', year: 'numeric' }),
    totalNiches: dailyRanked.length
  };
}
